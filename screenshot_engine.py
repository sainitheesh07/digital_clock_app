class Canvas:
    def __init__(self, width=1280, height=720, bg_top=(15, 32, 39), bg_bottom=(44, 83, 100)):
        self.w = width
        self.h = height
        self.buf = bytearray(width * height * 3)
        # Fill linear gradient
        for y in range(height):
            ratio = y / max(1, height - 1)
            r = int(bg_top[0] + (bg_bottom[0] - bg_top[0]) * ratio)
            g = int(bg_top[1] + (bg_bottom[1] - bg_top[1]) * ratio)
            b = int(bg_top[2] + (bg_bottom[2] - bg_top[2]) * ratio)
            row_idx = y * width * 3
            for x in range(width):
                self.buf[row_idx + x * 3] = r
                self.buf[row_idx + x * 3 + 1] = g
                self.buf[row_idx + x * 3 + 2] = b

    def set_pixel(self, x, y, color):
        if 0 <= x < self.w and 0 <= y < self.h:
            idx = (y * self.w + x) * 3
            self.buf[idx] = color[0]
            self.buf[idx + 1] = color[1]
            self.buf[idx + 2] = color[2]

    def fill_rect(self, x1, y1, x2, y2, color):
        x1, x2 = max(0, int(min(x1, x2))), min(self.w, int(max(x1, x2)))
        y1, y2 = max(0, int(min(y1, y2))), min(self.h, int(max(y1, y2)))
        for y in range(y1, y2):
            idx = (y * self.w + x1) * 3
            for x in range(x1, x2):
                self.buf[idx] = color[0]
                self.buf[idx + 1] = color[1]
                self.buf[idx + 2] = color[2]
                idx += 3

    def draw_rect(self, x1, y1, x2, y2, color, thickness=1):
        self.fill_rect(x1, y1, x2, y1 + thickness, color)
        self.fill_rect(x1, y2 - thickness, x2, y2, color)
        self.fill_rect(x1, y1, x1 + thickness, y2, color)
        self.fill_rect(x2 - thickness, y1, x2, y2, color)

    def draw_card(self, x1, y1, x2, y2, bg_color=(20, 35, 45), border_color=(0, 229, 255), border_thick=1):
        self.fill_rect(x1, y1, x2, y2, bg_color)
        if border_thick > 0:
            self.draw_rect(x1, y1, x2, y2, border_color, border_thick)

    def draw_text(self, text, x, y, color=(255, 255, 255), scale=2):
        curr_x = x
        for ch in text:
            cols = FONT.get(ch, FONT.get('?'))
            for col_idx, col_bits in enumerate(cols):
                for row_idx in range(7):
                    if (col_bits >> row_idx) & 1:
                        px = curr_x + col_idx * scale
                        py = y + row_idx * scale
                        for dy in range(scale):
                            for dx in range(scale):
                                self.set_pixel(px + dx, py + dy, color)
            curr_x += (len(cols) + 1) * scale

    def draw_window_header(self, title, x1=40, y1=30, x2=1240, y2=75):
        # Window Header Bar
        self.fill_rect(x1, y1, x2, y2, (32, 58, 67))
        self.draw_rect(x1, y1, x2, y2, (0, 229, 255), 1)
        # Window Buttons (Red, Yellow, Green dots)
        self.fill_rect(x1 + 15, y1 + 15, x1 + 27, y1 + 27, (255, 95, 87))
        self.fill_rect(x1 + 35, y1 + 15, x1 + 47, y1 + 27, (254, 188, 46))
        self.fill_rect(x1 + 55, y1 + 15, x1 + 67, y1 + 27, (40, 201, 64))
        # Title text
        self.draw_text(title, x1 + 85, y1 + 14, (0, 229, 255), scale=2)

    def save_png(self, filename):
        def chunk(chunk_type, data):
            return struct.pack('>I', len(data)) + chunk_type + data + struct.pack('>I', zlib.crc32(chunk_type + data) & 0xffffffff)

        header = b'\x89PNG\r\n\x1a\n'
        ihdr = chunk(b'IHDR', struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0))
        raw_rows = []
        for y in range(self.h):
            raw_rows.append(b'\x00' + bytes(self.buf[y * self.w * 3 : (y + 1) * self.w * 3]))
        raw_data = b''.join(raw_rows)
        idat = chunk(b'IDAT', zlib.compress(raw_data, 6))
        iend = chunk(b'IEND', b'')

        os.makedirs(os.path.dirname(os.path.abspath(filename)), exist_ok=True)
        with open(filename, 'wb') as f:
            f.write(header + ihdr + idat + iend)
        print(f"Generated: {filename} ({self.w}x{self.h})")

